/**
 * Every icon the product ships, generated from ONE master mark.
 *
 *   node scripts/make-brand-assets.mjs <mark.svg> [--scale 0.66] [--dy -1] [--out <dir>] [--flat]
 *
 * WHY ONE SCRIPT. The mark lives in six raster/vector files (tab icon, iOS
 * icon, two PWA icons, the push badge, the SVG the app links) and four inline
 * copies. The last logo was hand-exported into each, and they drifted: the
 * favicon's stem was thicker than the app icon's, the badge was a different
 * silhouette. A logo change is one file plus this script, or it is a week of
 * finding the copies.
 *
 * WHAT IT MAKES
 *   src/app/icon.svg        mark on the rounded teal tile — the browser tab
 *                           and PWA source Next.js serves
 *   src/app/favicon.ico     16 / 32 / 48 frames of the same tile
 *   src/app/apple-icon.png  180×180, tile, no transparency (iOS composites
 *                           its own corner radius)
 *   public/icon-192.png     PWA
 *   public/icon-512.png     PWA
 *   public/icon-badge.png   96×96, the bare mark in WHITE on transparent —
 *                           Android draws a push badge as a monochrome
 *                           silhouette and ignores colour
 *
 * The mark must be the BARE mark (no tile) in a 64-unit viewBox. --scale is
 * the fraction of the tile the mark's box spans; --dy nudges it in units
 * because a flat-bottomed or top-heavy mark is not centred at its box centre.
 * Take both numbers from the mark's CONSTRUCTION.md.
 *
 * ICO is written here rather than pulled in as a dependency: the format is a
 * 6-byte header, 16 bytes per frame, then the frames — and frames may be
 * PNG, which every browser since IE11 reads. Twenty lines beats a package.
 */

import { createRequire } from "node:module";
import { readFileSync, writeFileSync } from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const here = path.dirname(fileURLToPath(import.meta.url));
const root = path.resolve(here, "..");
const sharp = createRequire(path.join(root, "package.json"))("sharp");

const args = process.argv.slice(2);
const markPath = args.find((a, i) => !a.startsWith("--") && !(i > 0 && args[i - 1].startsWith("--")));
if (!markPath) {
  console.error("usage: node scripts/make-brand-assets.mjs <mark.svg> [--scale 0.66] [--dy -1] [--out <dir>] [--flat]");
  process.exit(1);
}
const opt = (name, dflt) => {
  const i = args.indexOf(`--${name}`);
  return i >= 0 && args[i + 1] ? Number(args[i + 1]) : dflt;
};
const SCALE = opt("scale", 0.66);
const DY = opt("dy", 0);

const TEAL = "#19819A";
// The tile the product has always used is a diagonal teal gradient, not a flat
// fill. --flat opts out; the gradient is the default because it is what the
// crèche's staff and parents already recognise on their phones.
const GRAD = ["#006F8F", "#008DA1", "#31B7BC"];
const FLAT = args.includes("--flat");
const mark = readFileSync(markPath, "utf8");

// The mark's own <svg> wrapper goes; its contents are nested into the tile.
const inner = mark
  .replace(/<\?xml[^>]*>/, "")
  .replace(/<!--[\s\S]*?-->/g, "")
  .replace(/<svg[^>]*>/, "")
  .replace(/<\/svg>\s*$/, "")
  .trim();
const vb = /viewBox="0 0 (\d+) (\d+)"/.exec(mark);
const unit = vb ? Number(vb[1]) : 64;
if (!vb || Number(vb[1]) !== Number(vb[2])) {
  console.error("the mark must have a square viewBox (0 0 N N)");
  process.exit(1);
}

/** Mark centred on a rounded square. The offset is in mark units. */
function tileSvg() {
  const s = (64 * SCALE) / unit;
  const off = (64 - unit * s) / 2;
  const bg = FLAT
    ? `<rect width="64" height="64" rx="14" fill="${TEAL}"/>`
    : `<defs><linearGradient id="tile" x1="0" y1="0" x2="1" y2="1">` +
      `<stop offset="0" stop-color="${GRAD[0]}"/>` +
      `<stop offset=".52" stop-color="${GRAD[1]}"/>` +
      `<stop offset="1" stop-color="${GRAD[2]}"/>` +
      `</linearGradient></defs>\n  <rect width="64" height="64" rx="14" fill="url(#tile)"/>`;
  // The mark is drawn in the brand teal so it reads on its own; on the tile it
  // must be white. Recolour here rather than keeping two master files.
  const onTile = inner
    .replace(/fill="(?!none|url)[^"]*"/g, 'fill="#ffffff"')
    .replace(/stroke="(?!none|url)[^"]*"/g, 'stroke="#ffffff"')
    .replace(/stop-color="[^"]*"/g, 'stop-color="#ffffff"');
  return `<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 64 64" role="img" aria-label="Rawdatik">
  <!-- Generated by scripts/make-brand-assets.mjs from ${path.basename(markPath)}. Do not hand-edit; change the mark and re-run. -->
  ${bg}
  <g transform="translate(${off.toFixed(3)} ${(off + DY * s).toFixed(3)}) scale(${s.toFixed(4)})">
${onTile.split("\n").map((l) => "    " + l).join("\n")}
  </g>
</svg>
`;
}

/** The bare mark forced to white — for the monochrome push badge. */
function whiteMarkSvg() {
  const white = inner
    .replace(/fill="(?!none)[^"]*"/g, 'fill="#ffffff"')
    .replace(/stroke="(?!none)[^"]*"/g, 'stroke="#ffffff"')
    .replace(/stop-color="[^"]*"/g, 'stop-color="#ffffff"')
    .replace(/(?<![-\\w])opacity="[^"]*"/g, "")
    .replace(/stop-opacity="[^"]*"/g, 'stop-opacity="1"');
  return `<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 ${unit} ${unit}">${white}</svg>`;
}

async function png(svg, size, { flatten = false } = {}) {
  let img = sharp(Buffer.from(svg), { density: (size / 64) * 72 * 4 }).resize(size, size);
  if (flatten) img = img.flatten({ background: TEAL });
  return img.png().toBuffer();
}

/** ICO container around PNG frames. */
function ico(frames) {
  const header = Buffer.alloc(6);
  header.writeUInt16LE(0, 0);             // reserved
  header.writeUInt16LE(1, 2);             // type: icon
  header.writeUInt16LE(frames.length, 4); // count
  const dir = Buffer.alloc(16 * frames.length);
  let offset = 6 + dir.length;
  frames.forEach(({ size, buf }, i) => {
    const e = 16 * i;
    dir.writeUInt8(size === 256 ? 0 : size, e);     // width  (0 means 256)
    dir.writeUInt8(size === 256 ? 0 : size, e + 1); // height
    dir.writeUInt8(0, e + 2);                       // palette
    dir.writeUInt8(0, e + 3);                       // reserved
    dir.writeUInt16LE(1, e + 4);                    // planes
    dir.writeUInt16LE(32, e + 6);                   // bpp
    dir.writeUInt32LE(buf.length, e + 8);           // bytes
    dir.writeUInt32LE(offset, e + 12);              // offset
    offset += buf.length;
  });
  return Buffer.concat([header, dir, ...frames.map((f) => f.buf)]);
}

const tile = tileSvg();
const outIdx = args.indexOf("--out");
const outRoot = outIdx >= 0 && args[outIdx + 1] ? path.resolve(args[outIdx + 1]) : root;
const { mkdirSync } = await import("node:fs");
const out = (p) => { const f = path.join(outRoot, p); mkdirSync(path.dirname(f), { recursive: true }); return f; };

writeFileSync(out("src/app/icon.svg"), tile);
writeFileSync(out("src/app/favicon.ico"), ico(await Promise.all(
  [16, 32, 48].map(async (size) => ({ size, buf: await png(tile, size) }))
)));
writeFileSync(out("src/app/apple-icon.png"), await png(tile, 180, { flatten: true }));
writeFileSync(out("public/icon-192.png"), await png(tile, 192));
writeFileSync(out("public/icon-512.png"), await png(tile, 512));
writeFileSync(out("public/icon-badge.png"), await png(whiteMarkSvg(), 96));

console.log(`brand assets regenerated from ${markPath}  (scale ${SCALE}, dy ${DY})`);
for (const p of ["src/app/icon.svg", "src/app/favicon.ico", "src/app/apple-icon.png",
                 "public/icon-192.png", "public/icon-512.png", "public/icon-badge.png"]) {
  console.log(`  ${p}`);
}
console.log("\nStill by hand — the inline copies of the mark:");
console.log("  src/components/landing/wordmark.tsx, public/guide.html, public/quickstart.html, public/media-kit.html");
